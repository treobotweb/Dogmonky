// ======================================================

function lookupPattern(history) {
  if (!history.length) {
    return null;
  }

  const seq = history.map((h) =>
    h.result === 'Tài'
      ? 'T'
      : 'X'
  );

  for (
    let len = Math.min(8, seq.length);
    len >= 1;
    len--
  ) {
    const key = seq
      .slice(-len)
      .join('');

    if (
      Object.prototype.hasOwnProperty.call(
        PATTERN_TABLE,
        key
      )
    ) {
      return {
        prediction: PATTERN_TABLE[key],
        matchLen: len,
        key
      };
    }
  }

  return null;
}

