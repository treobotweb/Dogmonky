// TAIXIU (đã nâng cấp với dự đoán VIP và thống kê chi tiết)
// ======================================================

app.get('/taixiu', async (req, res) => {
  try {
    const history =
      await fetchHistory();

    if (!history.length) {
      return res.json({
        error:
          'Không có dữ liệu'
      });
    }

    const current =
      history[history.length - 1];

    const nextPhien =
      current.phien + 1;

    // --- Dự đoán từ PATTERN_TABLE (giữ nguyên) ---
    const pattern =
      lookupPattern(history);

    let prediction;
    let confidence;
    let method;

    if (pattern) {
      prediction =
        pattern.prediction;

      confidence = Math.min(
        55 +
          pattern.matchLen * 4,
        92
      );

      method = `pattern_${pattern.matchLen}`;
    } else {
      const fallback =
        fallbackPredict(history);

      prediction =
        fallback.prediction;

      confidence =
        fallback.confidence;

      method = 'fallback';
    }

    // --- Dự đoán VIP từ hệ thống nâng cao ---
    // Đảm bảo advancedPredictor đã được đồng bộ (đã gọi sync trong fetchHistory)
    const vipPrediction = advancedPredictor.getFinalPrediction();
    let vipKetQua = null;
    let vipTinCay = 0;
    if (vipPrediction && vipPrediction.prediction) {
      vipKetQua = vipPrediction.prediction === 'T' ? 'Tài' : 'Xỉu';
      vipTinCay = Math.round(vipPrediction.confidence * 100);
    }

    // --- Lưu log dự đoán ---
    const exists =
      predictionLog.find(
        (x) =>
          x.phien === nextPhien
      );

    if (!exists) {
      predictionLog.push({
        phien: nextPhien,
        duDoan: prediction,
        ketQuaThuc: null,
        dungSai: null,
        time:
          new Date().toISOString()
      });
    }

    // --- Thống kê chi tiết (chuỗi thắng/thua) ---
    const detailedStats = calculateDetailedStats();

    res.json({
      phien_du_doan:
        nextPhien,

      phien_vua_xong:
        current.phien,

      Ket_qua:
        current.result,

      Tong:
        current.tong,

      Xuc_xac_1:
        current.dices[0],

      Xuc_xac_2:
        current.dices[1],

      Xuc_xac_3:
        current.dices[2],

      du_doan:
        prediction,

      do_tin_cay:
        `${Math.round(
          confidence
        )}%`,

      phuong_phap:
        method,

      thong_ke_du_doan:
        getAccuracyStats(),

      // Thêm phần dự đoán VIP
      du_doan_vip: {
        phien_tiep_theo: nextPhien,
        ket_qua: vipKetQua || 'Không xác định',
        ti_le_tin_cay: vipTinCay ? `${vipTinCay}%` : '0%',
        thuat_toan_hoat_dong: "113 Modules + MD5 Python + 1000+ Dynamic Patterns"
      },

      // Thêm thống kê học tập chi tiết
      thong_ke_hoc_tap_lc79: detailedStats,

      tong_phien_lich_su:
        history.length,

      thoi_gian:
        new Date().toISOString()
    });
  } catch (error) {
    console.error(error);

    res.status(500).json({
      error:
        error.message
    });
  }
});

