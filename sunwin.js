// ======================================================
// FETCH HISTORY
// ======================================================

async function fetchHistory() {
  const now = Date.now();

  if (
    now - lastFetchTime < CACHE_TTL &&
    cachedHistory.length > 0
  ) {
    return cachedHistory;
  }

  try {
    const response = await axios.get(API_URL, {
      timeout: 10000,
      headers: {
        'User-Agent': 'Mozilla/5.0'
      }
    });

    const raw = response.data;

    let arr = [];

    if (Array.isArray(raw)) {
      arr = raw;
    } else if (Array.isArray(raw.data)) {
      arr = raw.data;
    } else if (Array.isArray(raw.history)) {
      arr = raw.history;
    } else if (Array.isArray(raw.result)) {
      arr = raw.result;
    }

    const mapped = arr.map((item) => {
      let result =
        item.ketQuaThuc ||
        item.result ||
        item.ketqua ||
        item.ket_qua ||
        '';

      const dices = item.dices || item.dice || [
        Number(item.Xuc_xac_1 || item.xuc_xac_1 || 0),
        Number(item.Xuc_xac_2 || item.xuc_xac_2 || 0),
        Number(item.Xuc_xac_3 || item.xuc_xac_3 || 0)
      ];

      const tong =
        Number(item.tong || item.total || 0) ||
        dices.reduce((a, b) => a + b, 0);

      if (!result) {
        result = tong >= 11 ? 'Tài' : 'Xỉu';
      }

      return {
        phien: Number(
          item.phien ||
          item.session ||
          item.id ||
          0
        ),
        result,
        dices,
        tong,
        thoiGian:
          item.thoiGian ||
          item.time ||
          new Date().toISOString()
      };
    });

    const filtered = mapped.filter(
      (x) =>
        x.result === 'Tài' ||
        x.result === 'Xỉu'
    );

    filtered.sort((a, b) => a.phien - b.phien);

    cachedHistory = filtered;

    lastFetchTime = now;

    updatePredictionLog(filtered);

    // Đồng bộ dữ liệu vào hệ thống dự đoán nâng cao
    syncAdvancedPredictor(filtered);

    console.log(
      `[SUNWIN] fetched ${filtered.length} phiên`
    );

    return filtered;
  } catch (error) {
    console.error(
      '[SUNWIN] fetch error:',
      error.message
    );

    return cachedHistory;
  }
}

