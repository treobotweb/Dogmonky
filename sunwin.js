function updatePredictionLog(history) {
  predictionLog = predictionLog.map((entry) => {
    if (entry.dungSai) {
      return entry;
    }

    const found = history.find(
      (h) => h.phien === entry.phien
    );

    if (!found) {
      return entry;
    }

    return {
      ...entry,
      ketQuaThuc: found.result,
      dungSai:
        found.result === entry.duDoan
          ? 'Đúng'
          : 'Sai'
    };
  });
}

