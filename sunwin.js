function fallbackPredict(history) {
  if (history.length < 5) {
    return {
      prediction: 'Tài',
      confidence: 50
    };
  }

  const last5 = history.slice(-5);

  const tai = last5.filter(
    (x) => x.result === 'Tài'
  ).length;

  const xiu = last5.length - tai;

  if (tai > xiu) {
    return {
      prediction: 'Xỉu',
      confidence: 55
    };
  }

  if (xiu > tai) {
    return {
      prediction: 'Tài',
      confidence: 55
    };
  }

  return {
    prediction: 'Tài',
    confidence: 50
  };
}

